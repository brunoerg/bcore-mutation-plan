CPP = textwrap.dedent("""
    #include <x.h>
    namespace node {
    namespace {
    int Helper(int a)
    {
        return a + 1;
    }
    } // namespace

    class Widget
    {
    public:
        Widget(int v) : m_v(v) {}
        int Value() const { return m_v; }
        ~Widget() {}
    private:
        int m_v;
    };

    template <typename T>
    T Twice(T v)
    {
        return v * 2;
    }

    bool Widget::Check(int x) const EXCLUSIVE_LOCKS_REQUIRED(cs_main)
    {
        // comment
        return x > m_v;
    }

    bool operator==(const Widget& a, const Widget& b) { return a.Value() == b.Value(); }
    } // namespace node
""").lstrip("\n").encode()


def test_extract_functions_kinds_scopes_and_annotations():
    funcs, classes, _ = extract_functions(CPP)
    found = {f.name: f for f in funcs}
    assert {"Helper", "Widget", "Value", "~Widget", "Twice", "Widget::Check", "operator=="} <= set(found)
    assert found["Widget"].kind == "constructor"
    assert found["~Widget"].kind == "destructor"
    assert found["Value"].kind == "method"
    assert found["Widget::Check"].kind == "method"
    assert found["Helper"].kind == "function"
    assert found["operator=="].kind == "operator"
    assert found["Helper"].scope == ["node", "(anonymous)"]
    assert found["Value"].scope == ["node", "Widget"]
    # template declaration line is included in the function range
    assert CPP.decode().splitlines()[found["Twice"].start_line - 1].startswith("template")
    assert ("Widget", 10, 18) in classes


def test_neutralize_preserves_positions():
    src = b"void F() EXCLUSIVE_LOCKS_REQUIRED(::cs_main, m_pool.cs)\n{\n}\n"
    out = neutralize_annotations(src)
    assert len(out) == len(src) and out.count(b"\n") == src.count(b"\n")
    assert b"EXCLUSIVE" not in out


def test_changed_functions_attribution_and_fallback():
    lines = CPP.decode().splitlines()
    check_body = next(i for i, l in enumerate(lines, 1) if "return x > m_v" in l)
    comment_line = next(i for i, l in enumerate(lines, 1) if l.startswith("#include"))
    funcs, unattributed, notes, classes, ok = changed_functions(
        CPP,
        [LineRange(start=check_body, end=check_body), LineRange(start=comment_line, end=comment_line)],
        [],
        ContextLimits(),
    )
    assert ok
    assert [f.name for f in funcs] == ["Widget::Check"]
    assert funcs[0].changed_lines == [LineRange(start=check_body, end=check_body)]
    assert f"{check_body:>6}+|" in funcs[0].snippet
    assert unattributed == [LineRange(start=comment_line, end=comment_line)]


def test_deletion_inside_function_attributes_function():
    lines = CPP.decode().splitlines()
    anchor = next(i for i, l in enumerate(lines, 1) if "return a + 1" in l)
    funcs, unattributed, *_ = changed_functions(CPP, [], [anchor], ContextLimits())
    assert [f.name for f in funcs] == ["Helper"] and not unattributed


def test_rpc_name_and_long_function_snippet_truncation():
    body = "\n".join(f"    int v{i} = {i};" for i in range(300))
    src = f'static RPCMethod getthing()\n{{\n    return RPCMethod{{\n        "getthing",\n    }};\n{body}\n}}\n'.encode()
    funcs, *_ = changed_functions(src, [LineRange(start=150, end=150)], [], ContextLimits(max_function_snippet_lines=40))
    f = funcs[0]
    assert f.rpc_name == "getthing"
    assert f.snippet_truncated and "omitted" in f.snippet and "   150+|" in f.snippet


def test_interesting_literals():
    lits = interesting_literals([
        'throw JSONRPCError(RPC_WALLET_ERROR, "Insufficient funds for this transaction");',
        'argsman.AddArg("-maxmempool=<n>", ...); if (gArgs.IsArgSet("-maxmempool")) {}',
        '// "commented out string that is long"',
        'x = "short";',
    ])
    assert "Insufficient funds for this transaction" in lits
    assert "-maxmempool" in lits
    assert all("commented" not in s for s in lits) and "short" not in lits
