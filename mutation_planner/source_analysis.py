log = logging.getLogger(__name__)

CPP_SOURCE_EXT = {".cpp", ".cc", ".cxx", ".c", ".mm"}
CPP_HEADER_EXT = {".h", ".hpp", ".hxx", ".ipp", ".inl"}
DOC_EXT = {".md", ".rst", ".adoc", ".1", ".txt"}
DOC_NAMES = {"COPYING", "README", "CONTRIBUTING", "SECURITY", "INSTALL", "AUTHORS", "LICENSE"}
BUILD_NAMES = {
    "CMakeLists.txt", "CMakePresets.json", "vcpkg.json", "Makefile", "configure.ac",
    ".gitignore", ".gitattributes", ".editorconfig", ".clang-format", ".clang-tidy",
    ".python-version", ".cirrus.yml", ".style.yapf", "ruff.toml",
}
BUILD_EXT = {".cmake", ".mk", ".in", ".yml", ".yaml", ".toml", ".pc", ".am", ".m4"}
BUILD_PREFIXES = ("cmake/", "depends/", "ci/", ".github/", ".tx/")
TEST_DIR_NAMES = {"test", "tests"}
_GENERATED_BANNER = re.compile(
    r"(?i)(automatically generated|auto-generated|autogenerated|generated by|do not edit)"
)


def load_subtrees(lint_file_text: str | None, fallback: tuple[str, ...]) -> list[str]:
    """Read the subtree list from Bitcoin Core's lint config without executing it."""
    if lint_file_text:
        try:
            tree = ast.parse(lint_file_text)
            for node in ast.walk(tree):
                if isinstance(node, ast.Assign) and any(
                    isinstance(t, ast.Name) and t.id == "SHARED_EXCLUDED_SUBTREES" for t in node.targets
                ):
                    value = ast.literal_eval(node.value)
                    if isinstance(value, list) and all(isinstance(v, str) for v in value):
                        return [v if v.endswith("/") else v + "/" for v in value]
        except (SyntaxError, ValueError):
            log.warning("could not parse subtree list; using fallback")
    return list(fallback)


def classify_file(
    path: str,
    head_text: str | None,
    subtrees: list[str],
    conventions: RepoConventions,
) -> tuple[FileClass, str]:
    p = PurePosixPath(path)
    name, suffix = p.name, p.suffix.lower()
    parts = p.parts

    for st in subtrees:
        if path.startswith(st):
            return FileClass.third_party, f"inside vendored subtree {st}"
    for gen in conventions.known_generated:
        if path == gen or (gen.endswith("/") and path.startswith(gen)):
            return FileClass.generated, f"known generated path {gen}"
    if head_text is not None:
        head = "\n".join(head_text.splitlines()[:15])
        if _GENERATED_BANNER.search(head):
            return FileClass.generated, "generated-file banner in file header"

    if parts and parts[0] == "doc":
        return FileClass.documentation, "under doc/"
    if name in BUILD_NAMES or suffix in BUILD_EXT or path.startswith(BUILD_PREFIXES):
        return FileClass.build_config, "build or configuration file"
    if (suffix in DOC_EXT and suffix != ".txt") or name.split(".")[0] in DOC_NAMES:
        return FileClass.documentation, f"documentation file ({suffix or name})"

    if parts and parts[0] == "test":
        return FileClass.test_source, "under top-level test/"
    if any(part in TEST_DIR_NAMES for part in parts[:-1]):
        return FileClass.test_source, "inside a test directory"
    if suffix == ".txt":
        return FileClass.documentation, "plain-text file outside test directories"
    if path.startswith("src/bench/"):
        return FileClass.other, "benchmark source (not a regression test, not a mutation target)"

    if path.startswith(conventions.source_root):
        if suffix in CPP_SOURCE_EXT:
            return FileClass.production_cpp, "C++ implementation under src/ outside test directories"
        if suffix in CPP_HEADER_EXT:
            return FileClass.production_header, "C++ header under src/ outside test directories"
    return FileClass.other, "no production/test/doc/build rule matched"


