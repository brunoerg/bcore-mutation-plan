@lru_cache(maxsize=1)
def _parser():
    try:
        import tree_sitter_cpp
        from tree_sitter import Language, Parser
    except ImportError:  # pragma: no cover - dependency missing
        return None
    return Parser(Language(tree_sitter_cpp.language()))


@dataclass
class FunctionDef:
    name: str
    scope: list[str]
    start_line: int
    end_line: int
    kind: str
    body_text: str


_DECLARATOR_WRAPPERS = {
    "pointer_declarator", "reference_declarator", "attributed_declarator",
    "parenthesized_declarator", "init_declarator",
}
_SCOPE_TYPES = {"namespace_definition", "class_specifier", "struct_specifier", "union_specifier"}


def _function_name(node) -> str | None:
    decl = node.child_by_field_name("declarator")
    while decl is not None and decl.type != "function_declarator":
        if decl.type in _DECLARATOR_WRAPPERS:
            decl = decl.child_by_field_name("declarator")
        else:
            return None
    if decl is None:
        return None
    name_node = decl.child_by_field_name("declarator")
    if name_node is None:
        return None
    return " ".join(name_node.text.decode("utf-8", errors="replace").split())


def _scope_of(node) -> list[str]:
    scope: list[str] = []
    cur = node.parent
    while cur is not None:
        if cur.type in _SCOPE_TYPES:
            n = cur.child_by_field_name("name")
            scope.append(n.text.decode() if n is not None else "(anonymous)")
        cur = cur.parent
    return list(reversed(scope))


def _kind(name: str, scope: list[str], in_class: bool) -> str:
    short = name.split("::")[-1]
    if short.startswith("~"):
        return "destructor"
    if short.startswith("operator"):
        return "operator"
    parts = name.split("::")
    if (len(parts) >= 2 and parts[-1] == parts[-2]) or (in_class and scope and short == scope[-1]):
        return "constructor"
    if len(parts) >= 2 or in_class:
        return "method"
    return "function"


# Clang thread-safety and attribute macros that tree-sitter cannot parse after a
# declarator (e.g. ``void F() EXCLUSIVE_LOCKS_REQUIRED(cs_main) {``). They are blanked
# out with spaces before parsing so line/column positions are unchanged.
_ANNOTATION_MACROS = (
    "EXCLUSIVE_LOCKS_REQUIRED", "SHARED_LOCKS_REQUIRED", "LOCKS_EXCLUDED", "LOCK_RETURNED",
    "EXCLUSIVE_LOCK_FUNCTION", "SHARED_LOCK_FUNCTION", "UNLOCK_FUNCTION", "EXCLUSIVE_TRYLOCK_FUNCTION",
    "SHARED_TRYLOCK_FUNCTION", "ASSERT_EXCLUSIVE_LOCK", "ASSERT_SHARED_LOCK", "GUARDED_BY", "PT_GUARDED_BY",
    "ACQUIRED_AFTER", "ACQUIRED_BEFORE", "NO_THREAD_SAFETY_ANALYSIS", "LIFETIMEBOUND", "SCOPED_LOCKABLE", "LOCKABLE",
)
_ANNOT_RE = re.compile(rb"\b(" + b"|".join(m.encode() for m in _ANNOTATION_MACROS) + rb")\b")


def neutralize_annotations(source: bytes) -> bytes:
    buf = bytearray(source)
    for m in _ANNOT_RE.finditer(source):
        start, i = m.start(), m.end()
        j = i
        while j < len(buf) and buf[j] in b" \t":
            j += 1
        end = i
        if j < len(buf) and buf[j] == ord("("):
            depth, k = 0, j
            while k < len(buf):
                if buf[k] == ord("("):
                    depth += 1
                elif buf[k] == ord(")"):
                    depth -= 1
                    if depth == 0:
                        break
                k += 1
            end = k + 1
        for k in range(start, min(end, len(buf))):
            if buf[k] not in b"\r\n":
                buf[k] = ord(" ")
    return bytes(buf)


def extract_functions(source: bytes) -> tuple[list[FunctionDef], list[tuple[str, int, int]], list[str]]:
    """Return (function definitions, class definitions (name,start,end), parse notes)."""
    parser = _parser()
    if parser is None:
        return [], [], ["tree-sitter-cpp unavailable; using line ranges only"]
    tree = parser.parse(neutralize_annotations(source))
    funcs: list[FunctionDef] = []
    classes: list[tuple[str, int, int]] = []
    notes: list[str] = []
    if tree.root_node.has_error:
        notes.append("parser reported recoverable syntax errors (often macros); some functions may be unattributed")

    stack = [tree.root_node]
    while stack:
        node = stack.pop()
        if node.type == "function_definition":
            name = _function_name(node)
            if name:
                outer = node.parent if node.parent is not None and node.parent.type == "template_declaration" else node
                scope = _scope_of(node)
                in_class = node.parent is not None and node.parent.type == "field_declaration_list"
                funcs.append(
                    FunctionDef(
                        name=name,
                        scope=scope,
                        start_line=outer.start_point[0] + 1,
                        end_line=node.end_point[0] + 1,
                        kind=_kind(name, scope, in_class),
                        body_text=source[node.start_byte : node.end_byte].decode("utf-8", errors="replace"),
                    )
                )
        elif node.type in ("class_specifier", "struct_specifier"):
            n = node.child_by_field_name("name")
            if n is not None and node.child_by_field_name("body") is not None:
                classes.append((n.text.decode(), node.start_point[0] + 1, node.end_point[0] + 1))
        stack.extend(node.children)
    funcs.sort(key=lambda f: (f.start_line, -f.end_line))
    return funcs, classes, notes


_RPC_RE = re.compile(r"\b(?:RPCMethod|RPCHelpMan)\s*\{\s*\"([A-Za-z][A-Za-z0-9_]*)\"")
_STRING_RE = re.compile(r'"((?:[^"\\\n]|\\.)*)"')


def rpc_name_in(text: str) -> str | None:
    m = _RPC_RE.search(text)
    return m.group(1) if m else None


def interesting_literals(lines: list[str]) -> list[str]:
    """String literals worth searching for in tests: messages, option names, RPC fields."""
    out: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith(("//", "#include", "LogDebug", "LogTrace")):
            continue
        for m in _STRING_RE.finditer(line):
            s = m.group(1)
            if "\\" in s or "%" in s and len(s) < 16:
                continue
            if re.fullmatch(r"-[a-z][a-z0-9]{3,}", s) or (len(s) >= 12 and " " in s and re.search(r"[A-Za-z]{3}", s)):
                if s not in out:
                    out.append(s)
    return out[:15]


def _innermost(funcs: list[FunctionDef], line: int) -> FunctionDef | None:
    best = None
    for f in funcs:
        if f.start_line <= line <= f.end_line and (best is None or f.end_line - f.start_line < best.end_line - best.start_line):
            best = f
    return best


def format_snippet(lines: list[str], start: int, end: int, changed: set[int]) -> str:
    """Render lines [start, end] (1-based, inclusive) with line numbers; '+' marks changed lines."""
    return "\n".join(
        f"{n:>6}{'+' if n in changed else ' '}| {lines[n - 1]}" for n in range(start, min(end, len(lines)) + 1)
    )


def windowed_snippet(
    lines: list[str], start: int, end: int, changed: set[int], max_lines: int, ctx: int
) -> tuple[str, bool]:
    """Snippet of [start,end]; when too long keep signature + windows around changed lines."""
    if end - start + 1 <= max_lines:
        return format_snippet(lines, start, end, changed), False
    keep: set[int] = set(range(start, min(start + 3, end + 1)))
    for n in changed:
        if start <= n <= end:
            keep.update(range(max(start, n - ctx), min(end, n + ctx) + 1))
    keep.add(end)
    parts: list[str] = []
    prev = None
    for n in sorted(keep):
        if prev is not None and n != prev + 1:
            parts.append(f"   ... [{n - prev - 1} unchanged lines omitted] ...")
        parts.append(format_snippet(lines, n, n, changed))
        prev = n
    return "\n".join(parts), True


def changed_functions(
    source: bytes,
    changed_lines: list[LineRange],
    deletion_anchors: list[int],
    limits: ContextLimits,
) -> tuple[list[ChangedFunction], list[LineRange], list[str], list[tuple[str, int, int]], bool]:
    """Attribute changed lines to enclosing functions.

    Returns (functions, unattributed ranges, notes, classes, parse_ok).
    """
    text = source.decode("utf-8", errors="replace")
    lines = text.splitlines()
    funcs, classes, notes = extract_functions(source)
    parse_ok = _parser() is not None

    touched: dict[int, tuple[FunctionDef, list[int]]] = {}
    unattributed: list[int] = []
    changed_set: set[int] = set()
    for r in changed_lines:
        changed_set.update(range(r.start, r.end + 1))
    for ln in sorted(changed_set | set(deletion_anchors)):
        f = _innermost(funcs, ln)
        if f is None:
            if ln in changed_set:
                unattributed.append(ln)
            continue
        touched.setdefault(id(f), (f, []))[1].append(ln)

    result: list[ChangedFunction] = []
    for f, lns in sorted(touched.values(), key=lambda t: t[0].start_line):
        fn_changed = [ln for ln in lns if ln in changed_set]
        ranges = _ranges(fn_changed) or _ranges(lns)
        snippet, truncated = windowed_snippet(
            lines, f.start_line, f.end_line, changed_set,
            limits.max_function_snippet_lines, limits.snippet_context_lines,
        )
        result.append(
            ChangedFunction(
                name=f.name,
                short_name=f.name.split("::")[-1],
                enclosing_scope=f.scope,
                kind=f.kind,  # type: ignore[arg-type]
                start_line=f.start_line,
                end_line=f.end_line,
                changed_lines=ranges,
                rpc_name=rpc_name_in(f.body_text),
                snippet=snippet,
                snippet_start_line=f.start_line,
                snippet_truncated=truncated,
            )
        )
    return result, _ranges(unattributed), notes, classes, parse_ok


def _ranges(lines: list[int]) -> list[LineRange]:
    out: list[LineRange] = []
    for ln in sorted(set(lines)):
        if out and ln == out[-1].end + 1:
            out[-1] = LineRange(start=out[-1].start, end=ln)
        else:
            out.append(LineRange(start=ln, end=ln))
    return out


_IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def is_specific_symbol(name: str, min_len: int) -> bool:
    """Reject identifiers too generic to be meaningful evidence on their own."""
    generic = {
        "operator", "main", "Init", "Run", "Get", "Set", "size", "empty", "clear", "begin", "end",
        "Serialize", "Unserialize", "SerializationOp", "ToString", "GetHash", "IsNull", "SetNull",
        "Reset", "Start", "Stop", "Interrupt", "Flush", "Check", "Process", "Update", "Load",
        "Write", "Read", "Add", "Remove", "Erase", "Find", "Contains", "Clear", "Lookup", "Empty",
        "Size", "Count",
    }
    return len(name) >= min_len and name not in generic and bool(_IDENT_RE.fullmatch(name))
